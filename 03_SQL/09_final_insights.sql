1. OVERALL BUSINESS PERFORMANCE

- The analysis includes a total of 10,293 customers.
- The total transaction amount generated was $45.53 million.
- Customers completed approximately 667,234 transactions.
- The average credit limit was $8,642.41.
- Total interest earned was $7.98 million.

---------------------------------------------------------

2. CARD CATEGORY PERFORMANCE

- The Blue card category was the strongest-performing segment, 
- generating the highest transaction amount of $37.84 million and 
- the highest interest revenue of $6.61 million. 
- Despite having a lower average credit limit of $7,291.73, 
- the Blue card segment accounted for the majority of overall business activity.

---------------------------------------------------------

3. EXPENSE TYPE ANALYSIS

- Bills was the highest-performing expense category.
- It generated approximately $11.17 million in transaction value.
- Customers completed approximately 178,025 transactions in
  this category.
- This suggests that bill payments are a significant driver of
  overall credit card usage.

---------------------------------------------------------

4. CUSTOMER DEMOGRAPHIC ANALYSIS

- Male customers generated higher transaction activity compared
  with female customers.
- Customers with a Graduate education level performed better
  than those with a High School education level.
- Married customers generated higher transaction activity than
  single customers.

---------------------------------------------------------

5. CUSTOMER JOB ANALYSIS

- Businessman was the highest-performing job category.
- Customers in this segment generated approximately $14.54 million
  in total transaction amount.
- This was significantly higher than the White-collar segment,
  which generated approximately $8.36 million.

---------------------------------------------------------

6. ASSET OWNERSHIP ANALYSIS

- Customers who do not own a car generated higher overall
  transaction activity compared with car owners.
- Customers who do not own a house also demonstrated stronger
  performance and generated higher average interest.

---------------------------------------------------------

7. AGE AND INCOME ANALYSIS

- Customers aged 46–55 were the highest-performing age group
  based on transaction activity.
- The Very High income group demonstrated the strongest overall
  performance among income segments.

---------------------------------------------------------

8. RISK AND DELINQUENCY ANALYSIS

- The overall delinquency rate was 6.06%.
- Government employees recorded the highest delinquency rate
  among job categories at 7.27%.
- Customers aged 18–25 represented the highest-risk age group,
  with a delinquency rate of 10%.
- The High income group recorded the highest delinquency rate
  among the income segments at 6.47%.

---------------------------------------------------------

9. KEY BUSINESS CONCLUSION

- The business generates strong transaction activity from Blue
  card customers, customers aged 46–55, and Very High income
  customers.
- Bills represent the largest spending category, making them an
  important driver of credit card usage.
- Businessmen are the highest-value customer segment based on
  transaction amount.
- However, younger customers aged 18–25 and Government employees
  show relatively higher delinquency rates and may require closer
  credit risk monitoring.

